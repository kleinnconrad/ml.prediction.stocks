"""
Generates docs/feature_engineering.sql, a SQL reference of the Step 1 inputs: the
per-stock features on each stock's own trading days, the forward return and target, the
alignment on the union calendar, the eligibility rule and the within-date percentile
ranks (with the neutral rank 0 for a missing value). The pipeline computes the same
columns in pandas (src/processing/features.py). The reference covers the features of
`step1_features`; the other candidates of the feature registry have no SQL template.

Run from the repository root: uv run --locked python docs/generate_sql.py
"""
import logging
import sys
from pathlib import Path
from typing import Callable, Dict, List

ROOT = Path(__file__).resolve().parents[1]
sys.path.append(str(ROOT))

from config.settings import load_settings  # noqa: E402
from src.processing.features import TRADED_VALUE_FEATURE, validate_feature_names  # noqa: E402

logger = logging.getLogger(__name__)

OUT_PATH = ROOT / 'docs' / 'feature_engineering.sql'
OWN = "(PARTITION BY ticker ORDER BY date)"


def window(rows: int) -> str:
    """Window over the stock's last `rows` own trading days including the current one."""
    return f"(PARTITION BY ticker ORDER BY date ROWS BETWEEN {rows - 1} PRECEDING AND CURRENT ROW)"


def full_window(column: str, rows: int, expression: str) -> str:
    """Wraps a rolling expression so it is NULL until the window holds `rows` values (pandas min_periods)."""
    return f"CASE WHEN COUNT({column}) OVER {window(rows)} = {rows} THEN {expression} END"


def period_return(periods: int) -> str:
    """SQL of the `periods`-day return."""
    return f"close / NULLIF(LAG(close, {periods}) OVER {OWN}, 0) - 1"


def distance_to_sma(rows: int) -> str:
    """SQL of the relative distance to the `rows`-day simple moving average."""
    return full_window('close', rows, f"close / NULLIF(AVG(close) OVER {window(rows)}, 0) - 1")


def volatility(rows: int) -> str:
    """SQL of the sample standard deviation of daily returns over `rows` days."""
    return full_window('daily_return', rows, f"STDDEV_SAMP(daily_return) OVER {window(rows)}")


# One SQL expression per feature of src/processing/features.py:FEATURE_FUNCTIONS
FEATURE_SQL: Dict[str, Callable[[], str]] = {
    'ret_21': lambda: period_return(21),
    'ret_63': lambda: period_return(63),
    'ret_126': lambda: period_return(126),
    'mom_12_1': lambda: f"LAG(close, 21) OVER {OWN} / NULLIF(LAG(close, 252) OVER {OWN}, 0) - 1",
    'dist_sma50': lambda: distance_to_sma(50),
    'dist_sma200': lambda: distance_to_sma(200),
    'vol_21': lambda: volatility(21),
    'vol_126': lambda: volatility(126),
    'log_traded_value': lambda: full_window('close', 126, f"LN(1 + AVG(close * volume) OVER {window(126)})"),
    'drawdown_252': lambda: full_window('close', 252, f"close / NULLIF(MAX(close) OVER {window(252)}, 0) - 1"),
}


def build_sql(feature_names: List[str], settings: Dict) -> str:
    """
    Builds the SQL reference for the given features and settings.

    Args:
        feature_names (List[str]): Model features (`step1_features`).
        settings (Dict): Loaded settings (horizon_days, threshold, step1_ffill_limit_days,
            step1_min_price_eur, step1_min_history_days).

    Returns:
        str: The SQL text.

    Raises:
        ValueError: On unknown features or features without an SQL template.
    """
    names = validate_feature_names(feature_names)
    missing = [name for name in names if name not in FEATURE_SQL]
    if missing:
        raise ValueError(f"No SQL template for the features {missing}; add them to FEATURE_SQL.")
    horizon = int(settings['horizon_days'])
    threshold = float(settings['threshold'])
    ffill_limit = int(settings['step1_ffill_limit_days'])
    min_price = float(settings['step1_min_price_eur'])
    min_history = int(settings['step1_min_history_days'])
    columns = list(dict.fromkeys(names + [TRADED_VALUE_FEATURE]))
    indent = "        "

    lines = [
        "-- ==============================================================================",
        "-- STEP 1 FEATURE ENGINEERING OF THE POOLED CROSS-SECTIONAL MODEL",
        "-- Generated by docs/generate_sql.py from src/processing/features.py and",
        "-- config/settings.yaml. Reference documentation: the pipeline computes the same",
        "-- columns in pandas.",
        "--",
        "-- Input: daily_prices(date, ticker, close, volume), one row per stock and trading day",
        "-- with an adjusted close (the stock's own trading days).",
        f"-- Settings: horizon_days = {horizon}, threshold = {threshold},",
        f"-- step1_ffill_limit_days = {ffill_limit}, step1_min_price_eur = {min_price},",
        f"-- step1_min_history_days = {min_history},",
        f"-- step1_features = {', '.join(names)}.",
        "-- ==============================================================================",
        "",
        "WITH own_days AS (",
        "    -- 1. The stock's own trading days; a missing volume counts as 0",
        "    SELECT",
        "        date,",
        "        ticker,",
        "        close,",
        "        COALESCE(volume, 0) AS volume,",
        f"        close / NULLIF(LAG(close, 1) OVER {OWN}, 0) - 1 AS daily_return",
        "    FROM daily_prices",
        "    WHERE close IS NOT NULL",
        "),",
        "",
        "stock_features AS (",
        "    -- 2. Features, forward return and label end date per stock. Every window counts",
        "    --    the stock's own trading days and is NULL until it is complete.",
        "    SELECT",
        "        date,",
        "        ticker,",
        "        close AS price,",
        f"        ROW_NUMBER() OVER {OWN} AS history_days,",
    ]
    for name in columns:
        lines.append(f"{indent}{FEATURE_SQL[name]()} AS {name},")
    lines += [
        f"        -- Forward return over horizon_days = {horizon} own trading days and its end date",
        f"        LEAD(close, {horizon}) OVER {OWN} / NULLIF(close, 0) - 1 AS fwd,",
        f"        LEAD(date, {horizon}) OVER {OWN} AS label_end",
        "    FROM own_days",
        "),",
        "",
        "calendar AS (",
        "    -- 3. Union calendar: every date on which at least one stock traded",
        "    SELECT date, ROW_NUMBER() OVER (ORDER BY date) AS day_no",
        "    FROM (SELECT DISTINCT date FROM own_days) AS dates",
        "),",
        "",
        "carried AS (",
        "    -- 4. A day without a trade carries the stock's last own trading day for at most",
        f"    --    step1_ffill_limit_days = {ffill_limit} days of the union calendar; the latest own row wins",
        "    SELECT",
        "        c.date,",
        "        f.ticker,",
        "        f.date AS last_trade,",
        "        f.price,",
        "        f.history_days,",
    ]
    lines += [f"        f.{name}," for name in columns]
    lines += [
        "        f.fwd,",
        "        f.label_end,",
        "        ROW_NUMBER() OVER (PARTITION BY c.date, f.ticker ORDER BY f.date DESC) AS recency",
        "    FROM calendar AS c",
        f"    JOIN calendar AS own ON own.day_no BETWEEN c.day_no - {ffill_limit} AND c.day_no",
        "    JOIN stock_features AS f ON f.date = own.date",
        "),",
        "",
        "eligible AS (",
        f"    -- 5. Eligibility (independent of the features): at least step1_min_history_days = {min_history}",
        "    --    own trading days up to the date, a positive 126-day traded value and a price above",
        f"    --    step1_min_price_eur = {min_price}; a stale stock has no carried row",
        "    SELECT *",
        "    FROM carried",
        "    WHERE recency = 1",
        f"      AND history_days >= {min_history}",
        f"      AND {TRADED_VALUE_FEATURE} > 0",
        f"      AND price > {min_price}",
        "),",
        "",
        "ranked AS (",
        "    -- 6. Within-date percentile rank minus 0.5 over the eligible stocks that have a value,",
        "    --    as pandas rank(pct=True, method='average'): ties share their average rank, so",
        "    --    pct = (RANK() + (ties - 1) / 2) / n. PERCENT_RANK() = (RANK() - 1) / (n - 1)",
        "    --    uses another scale and is not used. A missing value gets the neutral rank 0.",
        "    SELECT",
        "        e.*,",
    ]
    for i, name in enumerate(names):
        comma = "," if i < len(names) - 1 else ""
        lines += [
            f"        CASE WHEN {name} IS NULL THEN 0.0 ELSE",
            f"            (RANK() OVER (PARTITION BY date ORDER BY {name} NULLS LAST)",
            f"                + (COUNT(*) OVER (PARTITION BY date, {name}) - 1) / 2.0)",
            f"                / COUNT({name}) OVER (PARTITION BY date) - 0.5",
            f"        END AS r_{name}{comma}",
        ]
    lines += [
        "    FROM eligible AS e",
        "),",
        "",
        "month_ends AS (",
        "    -- 7. Training and validation use the last calendar date of every month",
        "    SELECT MAX(date) AS date",
        "    FROM calendar",
        "    GROUP BY EXTRACT(YEAR FROM date), EXTRACT(MONTH FROM date)",
        ")",
        "",
        "-- 8. Long panel with the binary target: 1 if the close horizon_days own trading days",
        f"--    later is at least threshold = {threshold} above the current close, NULL while unknown",
        "SELECT",
        "    r.*,",
        "    (r.date IN (SELECT date FROM month_ends)) AS is_month_end,",
        "    CASE",
        "        WHEN r.fwd IS NULL THEN NULL",
        f"        WHEN r.fwd >= {threshold} THEN 1.0",
        "        ELSE 0.0",
        "    END AS y",
        "FROM ranked AS r;",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Writes docs/feature_engineering.sql for the configured Step 1 features."""
    logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
    settings = load_settings()
    sql = build_sql(list(settings['step1_features']), settings)
    OUT_PATH.write_text(sql, encoding='utf-8')
    logger.info(f"Generated {OUT_PATH} ({len(sql.splitlines())} lines).")


if __name__ == "__main__":
    main()
